// 链路节点（与后端 graph.py 的 add_node 顺序一致）
// 后端推来的是中文 stage 文案（如 "生成sql"），这里做展示层的规范化
export const STAGES = [
  ["提取关键字", "提取关键字"],
  ["召回字段", "召回字段"],
  ["召回指标", "召回指标"],
  ["召回字段取值", "召回字段取值"],
  ["合并召回信息", "合并召回信息"],
  ["过滤指标", "过滤指标"],
  ["过滤表信息", "过滤表信息"],
  ["添加额外上下文", "添加额外上下文"],
  ["生成sql", "生成 SQL"],
  ["校验sql", "校验 SQL"],
  ["校正sql", "校正 SQL"],
  ["执行sql", "执行 SQL"],
];

const STAGE_LABEL = Object.fromEntries(STAGES);

// 三路召回是并行分支，推达顺序不固定，按文案查表即可，不绑定下标。
// 查不到时兜底美化（后端若改了文案，"xxx sql" 也能显示成 "xxx SQL"）
export function stageLabel(s) {
  const t = String(s ?? "").trim();
  if (STAGE_LABEL[t]) return STAGE_LABEL[t];
  return t.replace(/\s*(sql)\s*$/i, " SQL").replace(/\s+/g, " ");
}

